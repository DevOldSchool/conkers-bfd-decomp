def write_fixtures() -> None:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    for name, functions in FIXTURE_FUNCTIONS.items():
        (FIXTURES / name).write_text(listing(functions), encoding="utf-8")


if __name__ == "__main__":
    write_fixtures()
