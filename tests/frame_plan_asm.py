"""Tiny MIPS assembler for frame-plan test fixtures.

It encodes the handful of instruction shapes the fixtures use and renders them
as spimdisasm-style listings (``/* off vram WORD */  mnemonic operands``), so
hand-written fixtures carry correct machine words for ``scripts/frame_plan.py``.
Run as a module to regenerate ``tests/fixtures/frame_plan/*.s``.
"""

from __future__ import annotations

import re
from pathlib import Path

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "frame_plan"

GPR = {
    name: index for index, name in enumerate((
        "zero", "at", "v0", "v1", "a0", "a1", "a2", "a3",
        "t0", "t1", "t2", "t3", "t4", "t5", "t6", "t7",
        "s0", "s1", "s2", "s3", "s4", "s5", "s6", "s7",
        "t8", "t9", "k0", "k1", "gp", "sp", "fp", "ra",
    ))
}
MEMORY = {
    "lb": 0x20, "lh": 0x21, "lw": 0x23, "lbu": 0x24, "lhu": 0x25,
    "sb": 0x28, "sh": 0x29, "sw": 0x2B,
    "lwc1": 0x31, "ldc1": 0x35, "swc1": 0x39, "sdc1": 0x3D,
}
IMMEDIATE = {"addi": 0x08, "addiu": 0x09, "slti": 0x0A, "andi": 0x0C, "ori": 0x0D, "lui": 0x0F}
BRANCH = {"beq": 0x04, "bne": 0x05}
REGISTER_OPS = {"or": 0x25, "addu": 0x21, "subu": 0x23, "and": 0x24, "sll": 0x00}


def register(text: str) -> int:
    text = text.strip().lstrip("$")
    if text in GPR:
        return GPR[text]
    match = re.fullmatch(r"f(\d+)", text)
    if match:
        return int(match.group(1))
    raise ValueError(f"unknown register {text}")


def number(text: str) -> int:
    return int(text.strip(), 0)


def encode(instruction: str) -> int:
    """Encode one instruction such as ``sw $ra, 0x14($sp)`` or ``jal func_x``."""

    mnemonic, _, rest = instruction.strip().partition(" ")
    operands = [part.strip() for part in rest.split(",")] if rest.strip() else []
    if mnemonic == "nop":
        return 0
    if mnemonic == "jal":
        return (0x03 << 26) | (0x15000000 >> 2 & 0x3FFFFFF)
    if mnemonic == "jr":
        return (register(operands[0]) << 21) | 0x08
    if mnemonic == "jalr":
        return (register(operands[0]) << 21) | (31 << 11) | 0x09
    if mnemonic in MEMORY:
        match = re.fullmatch(r"(-?0x[0-9A-Fa-f]+|-?\d+)\((\$\w+)\)", operands[1])
        assert match, instruction
        offset, base = number(match.group(1)), register(match.group(2))
        return (MEMORY[mnemonic] << 26) | (base << 21) | (register(operands[0]) << 16) | (offset & 0xFFFF)
    if mnemonic == "lui":
        return (IMMEDIATE[mnemonic] << 26) | (register(operands[0]) << 16) | (number(operands[1]) & 0xFFFF)
    if mnemonic in IMMEDIATE:
        return ((IMMEDIATE[mnemonic] << 26) | (register(operands[1]) << 21)
                | (register(operands[0]) << 16) | (number(operands[2]) & 0xFFFF))
    if mnemonic in BRANCH:
        return (BRANCH[mnemonic] << 26) | (register(operands[0]) << 21) | (register(operands[1]) << 16) | 0xFFFF
    if mnemonic == "sll":
        return (register(operands[1]) << 16) | (register(operands[0]) << 11) | ((number(operands[2]) & 31) << 6)
    if mnemonic in REGISTER_OPS:
        return ((register(operands[1]) << 21) | (register(operands[2]) << 16)
                | (register(operands[0]) << 11) | REGISTER_OPS[mnemonic])
    if mnemonic == "mtc1":
        return (0x11 << 26) | (0x04 << 21) | (register(operands[0]) << 16) | (register(operands[1]) << 11)
    if mnemonic == "cvt.s.w":
        return (0x11 << 26) | (0x14 << 21) | (register(operands[1]) << 11) | (register(operands[0]) << 6) | 0x20
    raise ValueError(f"unsupported instruction: {instruction}")


def listing(functions: list[tuple[str, list[str]]], *, base: int = 0x15000000, preamble: bool = True) -> str:
    """Render functions as a reference listing; a line starting with ``.`` or ``glabel`` passes through."""

    lines = []
    if preamble:
        lines += [".include \"macro.inc\"", "", ".set noat", ".set noreorder", "",
                  ".section .text, \"ax\"", "", "/* Generated by frame_plan_asm */", ""]
    address = base
    for symbol, body in functions:
        lines.append(f"glabel {symbol}")
        for item in body:
            stripped = item.strip()
            if stripped.startswith((".", "glabel")):
                lines.append(("  " if stripped.startswith(".L") else "") + stripped if stripped.startswith(".L")
                             else stripped)
                continue
            word = encode(stripped)
            mnemonic, _, rest = stripped.partition(" ")
            lines.append(f"    /* {address - base:X} {address:08X} {word:08X} */  {mnemonic:<10} {rest.strip()}".rstrip())
            address += 4
    return "\n".join(lines) + "\n"


def words(body: list[str]) -> list[int]:
    return [encode(item) for item in body if not item.strip().startswith((".", "glabel"))]


