def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def restore_remaining_scene_corrections(test, canonical):
    """Validate exact five corrections before recreating the historical canonical subset."""
    for index, change in CANONICAL_CORRECTIONS.items():
        test.assertEqual(change["after"], canonical["models"][index])
        canonical["models"][index] = copy.deepcopy(change["before"])


